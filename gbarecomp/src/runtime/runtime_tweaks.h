// runtime_tweaks.h — built-in gameplay tweaks (engine-shipped ROM patch sets).
//
// Tweaks are binary patch sets applied to the in-memory ROM copy at boot,
// after SHA-1 verification and before any guest instruction runs (same
// boot-scoped path as content mods; the on-disk dump stays pristine).
// Selections persist in <mods_root>/selections.toml alongside content-mod
// selections and apply at the next game launch.
//
// The GP-slope-roll tweak redirects the ground-pound-landing pose handler
// (func_8011898, pose-handler table entries 53/54) to a helper installed in
// free ROM space. The helper probes the tile under Wario's feet via
// func_806DAC0 and requests WPOSE_NORMAL_STARTING_ROLL (12) when he lands on
// a slope tile (clip type 11); otherwise it runs the original animation
// stepper byte-for-byte. Patch bytes are generated by tools/wl4_tweak_gen.py
// from tools/tweaks/gp_slope_roll.s — do not edit by hand.
#pragma once

#include <cstdint>
#include <filesystem>
#include <string>
#include <vector>

namespace gbarecomp::runtime_tweaks {

struct Tweak {
    const char* id;           // stable identifier (selections.toml key)
    const char* name;         // settings-menu label
    const char* description;  // settings-menu blurb
};

// Registry, in menu order.
extern const std::vector<Tweak> kTweaks;

// Selected tweak ids persisted in <mods_root>/selections.toml (shared file
// with content mods; ids never collide because tweak ids are prefixed
// "tweak-").
std::vector<std::string> load_selections(
    const std::filesystem::path& mods_root);
bool save_selections(const std::filesystem::path& mods_root,
                     const std::vector<std::string>& ids);
bool selected(const std::filesystem::path& mods_root, const std::string& id);

// Apply every selected tweak's patch set to `rom` (which must be the
// verified USA dump). Each site is checked against its expected original
// bytes before writing; a mismatch appends to *log and is skipped. Returns
// the number of fully applied tweak patch sets.
int apply_enabled(std::uint8_t* rom, std::size_t rom_size,
                  const std::vector<std::string>& ids, std::string* log);

}  // namespace gbarecomp::runtime_tweaks