#!/usr/bin/env bash
# WarioLand4Recomp — full regeneration pipeline on Linux.
#
#   1. Verify the user-supplied Wario Land 4 (USA) ROM hash
#   2. Stamp its SHA-1 + CRC32 into the runtime configs (game.toml,
#      android/game_android.toml, src/main.cpp, android/app/build.gradle)
#   3. Build the wl4 decomp (agbcc) → byte-identical ROM + ELF + map
#   4. Import decomp symbols (functions + data) for the recompiler
#   5. Statically recompile the ROM into native C++ shards
#
# Usage: bash tools/regen.sh [--jobs N] [--skip-decomp]
# ROM is expected at roms/warioland4_usa.gba.

set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
JOBS=3
SKIP_DECOMP=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --jobs) JOBS="$2"; shift 2 ;;
        --skip-decomp) SKIP_DECOMP=1; shift ;;
        *) echo "unknown arg: $1"; exit 1 ;;
    esac
done

log() { printf '\n=== %s ===\n' "$*"; }

ROM="$ROOT/roms/warioland4_usa.gba"
DECOMP="$ROOT/decomp"
ENGINE="$ROOT/gbarecomp"
SYMS="$ROOT/variants/warioland4/symbols"
GEN="$ROOT/variants/warioland4/generated"
ELF="$DECOMP/build/us/warioland4_us.elf"
MAP="$DECOMP/build/us/warioland4_us.map"
RECOMPILER="$ENGINE/build/gba_recompile"

log "1/5 ROM identity"
[[ -f "$ROM" ]] || { echo "Missing $ROM — drop your legally dumped Wario Land 4 (USA) cartridge image there and rerun."; exit 1; }
ROM_MD5="$(md5sum "$ROM" | cut -d' ' -f1)"
if [[ "$ROM_MD5" != "5fe47355a33e3fabec2a1607af88a404" ]]; then
    echo "ROM md5 $ROM_MD5 is NOT Wario Land 4 (USA). Refusing to continue."; exit 1
fi
ROM_SHA1="$(sha1sum "$ROM" | cut -d' ' -f1)"
ROM_CRC32="$(python3 - "$ROM" <<'PY'
import sys, zlib
crc = 0
with open(sys.argv[1], 'rb') as f:
    while True:
        b = f.read(1 << 20)
        if not b: break
        crc = zlib.crc32(b, crc)
print(f"0x{crc:08X}")
PY
)"
echo "md5 ok; sha1=$ROM_SHA1 crc32=$ROM_CRC32"

log "2/5 Stamp runtime configs"
stamp() {  # stamp <file> — replace tokens with the real identity
    sed -i "s/@ROM_SHA1@/$ROM_SHA1/g; s/@ROM_CRC32@/$ROM_CRC32/g" "$1"
    echo "  stamped $1"
}
stamp "$ROOT/variants/warioland4/game.toml"
stamp "$ROOT/android/game_android.toml"
stamp "$ROOT/android/app/build.gradle"
chmod +x "$ROOT/android/gradlew"
cat > "$ROOT/src/wl4e_rom_identity.h" <<EOF
// wl4e_rom_identity.h — GENERATED by tools/regen.sh. Do not edit.
#pragma once
#define WL4E_ROM_SHA1 "$ROM_SHA1"
#define WL4E_ROM_CRC32 ${ROM_CRC32}u
EOF
echo "  generated src/wl4e_rom_identity.h"

if [[ $SKIP_DECOMP -eq 0 ]]; then
    log "3/5 Build the decomp (agbcc)"
    cp "$ROM" "$DECOMP/baserom_us.gba"
    if [[ ! -x "$DECOMP/tools/agbcc/agbcc" ]]; then
        (cd "$DECOMP/tools/agbcc" && ./build.sh)
    fi
    make -C "$DECOMP" tools
    make -C "$DECOMP" extract
    make -C "$DECOMP" -j"$JOBS"
    Built="$(md5sum "$DECOMP/build/us/warioland4_us.gba" | cut -d' ' -f1)"
    echo "decomp built: md5=$Built (expect 5fe47355a33e3fabec2a1607af88a404)"
    [[ "$Built" == "5fe47355a33e3fabec2a1607af88a404" ]] || {
        echo "Rebuilt ROM does not match the cartridge — aborting."; exit 1; }
fi

log "4/5 Symbol import"
mkdir -p "$SYMS"
arm-none-eabi-readelf -sW "$ELF"  > "$SYMS/WL4E_readelf_syms.txt"
arm-none-eabi-readelf -SW "$ELF"  > "$SYMS/WL4E_readelf_sections.txt"
cp "$MAP" "$SYMS/WL4E.map"
python3 "$ENGINE/tools/symbol_import/import_decomp_symbols.py" \
    --id WL4E --name "Wario Land 4 (USA)" \
    --syms "$SYMS/WL4E_readelf_syms.txt" \
    --sections "$SYMS/WL4E_readelf_sections.txt" \
    --map "$SYMS/WL4E.map" \
    --rom "$ROM" \
    --out "$SYMS"
echo "imported symbols in $SYMS"

log "5/5 gba_recompile"
if [[ ! -x "$RECOMPILER" ]]; then
    cmake -S "$ENGINE" -B "$ENGINE/build" -DCMAKE_BUILD_TYPE=Release
    cmake --build "$ENGINE/build" --target gba_recompile -j"$JOBS"
fi
mkdir -p "$GEN"
"$RECOMPILER" \
    --rom "$ROM" \
    --config "$ROOT/variants/warioland4/game.toml" \
    --config "$SYMS/WL4E_symbols.toml" \
    --symbols "$SYMS/imported_symbols.tsv" \
    --data-symbols "$SYMS/imported_data_symbols.tsv" \
    --out "$GEN"

cat <<DONE

Done. Generated code is in $GEN.

Next:
  Desktop build : cmake -S . -B build-desktop -DCMAKE_BUILD_TYPE=Release
                  cmake --build build-desktop -j1
  Run           : ./build-desktop/WarioLand4Recomp
                  (needs bios/gba_bios.bin = your GBA BIOS dump,
                   sha1 300c20df6731a33952ded8c436f7f186d25d3492)
DONE
